#!/usr/bin/env bash
# main(引数で別のコミットも指定できる)で関門を全件のE2Eつきで回す(ADR 0005)。関門がE2Eを差分の範囲に絞った分の取りこぼしを拾う。
# issue-loop.shが終了時に呼ぶほか、手でも実行できる。
#   scripts/full-check.sh [コミット]
# 本体チェックアウトの作業中の変更を混ぜないよう、専用のworktreeにmainを出して回す。
#
# 環境変数:
#   FULL_CHECK_ISSUE=1   失敗したらneeds-triageで起票する(openの起票が残っていればコメントを足す)
#   FULL_CHECK_MERGED    起票に載せる、このループで統合したIssue番号(空白区切り)
#   FULL_CHECK_PORT      E2Eのポート(既定3191。関門の3100〜、issue-verifyの3190と重ならないもの)
#   FULL_CHECK_LOG_DIR   ログ置き場(既定logs/full-check)
set -u
cd "$(dirname "$0")/.."
LOG_DIR="${FULL_CHECK_LOG_DIR:-logs/full-check}"
WT=".claude/worktrees/full-check"
TITLE="全件チェックがmainで失敗した"
mkdir -p "$LOG_DIR"
LOG="$PWD/$LOG_DIR/$(date +%Y%m%d-%H%M%S).log"
log() { echo "[$(date '+%H:%M:%S')] full-check: $*"; }

REF="${1:-main}"
sha=$(git rev-parse --short "$REF") || exit 5
if [ -d "$WT" ]; then git -C "$WT" checkout -q --detach "$sha"; else git worktree add -q --detach "$WT" "$sha"; fi || { log "worktreeを用意できません"; exit 5; }
# .env.localはローカルSupabaseのキー(issue-agent.shと同じ扱い)
[ -f .env.local ] && cp .env.local "$WT/.env.local"
log "$REF($sha)を全件で確認します($LOG)"
if (cd "$WT" && pnpm install --frozen-lockfile && CHECK_E2E=full E2E_PORT="${FULL_CHECK_PORT:-3191}" scripts/check.sh) >"$LOG" 2>&1; then
  log "通過($sha)"; exit 0
fi
log "失敗($sha)"
[ "${FULL_CHECK_ISSUE:-0}" = 1 ] || { tail -n 40 "$LOG"; exit 1; }

# Playwrightの要約(「N failed」に続く行)から落ちたspecを拾う。lintやビルドで止まったときは空になる
failed=$(sed -n '/^ *[0-9]* failed$/,/^ *[0-9]* \(flaky\|skipped\|did not run\|passed\)/p' "$LOG" | grep -oE 'e2e/[^ :]+\.spec\.ts' | sort -u)
body="> *This was generated by AI (full-check).*

\`$REF\`(\`$sha\`)で全件チェック(\`CHECK_E2E=full scripts/check.sh\`)が失敗しました。関門はE2Eを差分の範囲に絞っているので、範囲の外で壊れたテストはここで見つかります。

落ちたspec:
${failed:-(E2Eの前で止まりました。下のログを見てください)}

このループで統合したIssue: $(for n in ${FULL_CHECK_MERGED:-}; do printf '#%s ' "$n"; done)

ログ: \`$LOG\`

\`\`\`
$(tail -n 40 "$LOG")
\`\`\`"
open=$(gh issue list --state open --search "\"$TITLE\" in:title" --json number --jq '.[0].number // empty')
if [ -n "$open" ]; then
  printf '%s\n' "$body" | gh issue comment "$open" --body-file - >/dev/null && log "Issue #${open}にコメントしました"
else
  printf '%s\n' "$body" | gh issue create --title "$TITLE" --label bug --label needs-triage --body-file - && log "起票しました"
fi
exit 1
